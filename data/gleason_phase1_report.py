"""Phase 1 report: integrity checks + patch statistics for every built label set.

Usage:  python -I data/gleason_phase1_report.py --processed data/processed/gleason --out results/phase1_dataset
"""
import argparse
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

SETS = [("p512", "labels_benign-ignore"), ("p512", "labels_benign-drop"),
        ("p1024", "labels_benign-ignore"), ("p1024", "labels_benign-drop"),
        ("p512", "labels_benign-ignore_excl-r2")]
VOTE_COLS = {"r1", "r2", "r3", "r4", "r5", "r6", "votes_g4", "q", "majority_label", "tie"}


def kappa_from_cm(cm):
    n = cm.sum()
    po = np.trace(cm) / n
    pe = (cm.sum(0) * cm.sum(1)).sum() / n**2
    return (po - pe) / (1 - pe)


def check_integrity(d):
    """Assertions on the split files of one label set. Returns a list of check descriptions."""
    p = pd.read_csv(d / "patches.csv")
    done = []
    test_seen = []
    for fd in sorted((d / "folds").iterdir()):
        s = pd.read_csv(fd / "split.csv")
        assert len(s) == len(p) and set(s.patch_id) == set(p.patch_id)
        per_core = s.groupby("core_id").split.nunique()
        assert (per_core == 1).all(), f"{fd.name}: core in two splits"
        per_slide = s.groupby("group_id").split.apply(lambda x: set(x))
        test_slides = [g for g, v in per_slide.items() if "test" in v]
        assert all(per_slide[g] == {"test"} for g in test_slides), "test slide shared with train/val"
        assert len(test_slides) == 2
        test_seen += test_slides
        assert (s.loc[s.labelled == 1, "split"] == "train").all(), "labelled patch outside train"
        assert (s.loc[s.train_majority == 1, "labelled"] == 1).all()
        lab = pd.read_csv(fd / "labelled_list.csv")
        assert set(lab.patch_id) == set(s.loc[s.labelled == 1, "patch_id"])
        assert not lab.loc[lab.train_majority == 1, "tie"].any(), "tie used for majority training"
        for name in ["train_unlabelled", "val", "test"]:
            cols = set(pd.read_csv(fd / f"{name}.csv", nrows=1).columns)
            assert not (cols & VOTE_COLS), f"{name}.csv carries vote columns"
    assert sorted(test_seen) == sorted(p.group_id.unique()), "each slide must be test exactly once"
    done += ["every patch in exactly one split per fold", "no core spans two splits",
             "test slides disjoint from train/val; each slide is test in exactly one fold",
             "labelled patches only from train split", "ties excluded from majority training",
             "train_unlabelled/val/test files contain ids only (no votes)"]
    return done


def md_table(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--processed", default="data/processed/gleason")
    ap.add_argument("--out", default="results/phase1_dataset")
    args = ap.parse_args()
    root, out = Path(args.processed), Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    md = ["# Phase 1 report: Gleason2019 patch dataset\n",
          "Generated by `data/gleason_phase1_report.py`. Per-set details: "
          "`data/processed/gleason/p{T}/<set>/stats.json`.\n"]

    # ---- reader coverage after excluding empty masks --------------------------------------
    cr = pd.read_csv(root / "core_readers.csv")
    st = cr[[f"r{k}" for k in range(1, 7)]]
    ann = (st == "annotated")
    cr["n_readers"] = ann.sum(axis=1)
    md.append("## 1. Reader coverage per core (entirely-zero masks excluded)\n")
    md.append(f"Empty masks found and excluded: {int((st == 'empty').sum().sum())} "
              f"(per reader: {(st == 'empty').sum().to_dict()}).\n")
    md.append(f"Cores annotated per reader: {ann.sum().to_dict()}\n")
    md.append(f"Readers per core: {cr.n_readers.value_counts().sort_index().to_dict()}; "
              + ", ".join(f">={k}: {(cr.n_readers >= k).sum()}" for k in [3, 4, 5, 6]) + "\n")
    md.append(f"Otsu saturation threshold per core: median {cr.otsu_thr.median():.0f} "
              f"(range {cr.otsu_thr.min()}-{cr.otsu_thr.max()}); core tissue fraction median {cr.tissue_frac.median():.2f}.\n")

    # ---- pixel-level agreement on tissue, value 0 excluded ---------------------------------
    pc = pd.read_csv(root / "pixel_confusion.csv")
    rows = []
    for (a, b), g in pc.groupby(["reader_a", "reader_b"]):
        cm = g[[f"c{x}{y}" for x in range(4) for y in range(4)]].sum().to_numpy().reshape(4, 4).astype(float)
        cancer = cm[1:, 1:]
        bin_cm = np.array([[cancer[0, 0], cancer[0, 1:].sum()], [cancer[1:, 0].sum(), cancer[1:, 1:].sum()]])
        rows.append({"pair": f"r{a}-r{b}", "cores": g.core_id.nunique(),
                     "kappa_4cls(ben/3/4/5)": round(kappa_from_cm(cm), 3),
                     "kappa_G3_vs_G4+5 (both cancer)": round(kappa_from_cm(bin_cm), 3)})
    md.append("## 2. Pixel-level inter-reader agreement (tissue pixels where both readers are non-zero)\n")
    md.append(md_table(pd.DataFrame(rows)) + "\n")

    # ---- per label set -----------------------------------------------------------------------
    summary, checks = [], {}
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.5))
    for T, name in SETS:
        d = root / T / name
        if not d.exists():
            continue
        checks[f"{T}/{name}"] = check_integrity(d)
        s = json.load(open(d / "stats.json"))
        p = pd.read_csv(d / "patches.csv")
        summary.append({"tile": T, "set": name.replace("labels_", ""), "tissue tiles": s["n_tissue_tiles"],
                        "kept": s["n_kept"], "G3": s["class"]["g3"], "G4/5": s["class"]["g4"], "tie": s["class"]["tie"],
                        "unanimous": s["unanimous_frac"], "cores": s["n_cores_kept"], "mean q": s["q_mean"]})
        if name.endswith("ignore") and T in ("p512", "p1024"):
            ax = axes[0 if T == "p512" else 1]
            ax.hist(p.q, bins=np.linspace(0, 1, 13), color="#4a6fa5", edgecolor="white")
            ax.set_title(f"{T}, benign-ignore: q = votes_G4 / n_readers (n={len(p)})", fontsize=9)
            ax.set_xlabel("q")
    fig.tight_layout()
    fig.savefig(out / "q_hist.png", dpi=120)

    md.append("## 3. Patch counts per label set (keep if >= 3 valid G3 / G4-or-5 readers)\n")
    md.append(md_table(pd.DataFrame(summary)) + "\n")

    for T, name in SETS:
        d = root / T / name
        if not d.exists():
            continue
        s = json.load(open(d / "stats.json"))
        md.append(f"### {T} / {name}\n")
        md.append(f"- Funnel: {s['funnel']}")
        md.append(f"- Reader x tile raw labels: {s['raw_label_counts_reader_tile']}; 'none' because "
                  f"dominant=unannotated {s['none_reason']['dominant_unannotated']}, "
                  f"dominant<60% {s['none_reason']['dominant_below_coverage']}")
        md.append(f"- Readers per kept patch: {s['n_readers_hist']}")
        md.append(f"- q (votes/readers): {s['q_by_fraction']}")
        md.append(f"- q histogram: {s['q_hist']}; unanimous {s['unanimous_frac']} (non-tie {s['unanimous_frac_non_tie']})")
        rd = pd.DataFrame(s["readers"]).T.reset_index().rename(columns={"index": "reader"})
        md.append("\nPer-reader coverage on kept patches:\n\n" + md_table(rd))
        fr = []
        for f, fs in s["folds"].items():
            for part in ["train_labelled", "train_unlabelled", "val", "test"]:
                x = fs[part]
                fr.append({"fold": f, "test slides": "+".join(fs["test_slides"]), "part": part, "n": x["n"],
                           "G3": x["n_g3"], "G4/5": x["n_g4"], "tie": x["n_tie"],
                           "G4 rate": round(x["n_g4"] / max(1, x["n_g3"] + x["n_g4"]), 3),
                           "unanimous": x["unanimous_frac"], "cores": x["n_cores"]})
        md.append("\nPer fold / split:\n\n" + md_table(pd.DataFrame(fr)))
        md.append("\nAlternative unlabelled pool (all tissue tiles on train cores, no vote filter): "
                  + ", ".join(f"{f}: {fs['alt_unlabelled_pool_all_tissue']}" for f, fs in s["folds"].items()) + "\n")
        if T == "p512" and name == "labels_benign-ignore":
            pr = pd.DataFrame(s["pairwise_binary_agreement"]).T.reset_index().rename(columns={"index": "pair"})
            md.append("Patch-level binary agreement between readers (kept patches, both valid):\n\n" + md_table(pr) + "\n")

    md.append("## 4. Integrity checks (all passed)\n")
    for k, v in checks.items():
        md.append(f"- {k}: " + "; ".join(v))
    (out / "phase1_report.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
